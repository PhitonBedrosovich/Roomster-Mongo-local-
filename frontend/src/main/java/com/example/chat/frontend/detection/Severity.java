package com.example.chat.frontend.detection;

/**
 * Уровни серьезности обнаруженных чувствительных данных.
 */
public enum Severity {
    LOW,      // Низкая серьезность (например, email)
    MEDIUM,   // Средняя серьезность (например, телефон, ИНН)
    HIGH,     // Высокая серьезность (паспорт, карта, кошелек)
    CRITICAL  // Критическая серьезность (пароль, CVV, API токен)
}
